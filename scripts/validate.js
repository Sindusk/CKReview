const mode = rawArgs.includes('--check') ? 'check' : rawArgs.includes('--update') ? 'update' : 'run';
if (rawArgs.includes('--check') && rawArgs.includes('--update')) {
  console.error('--check and --update are mutually exclusive');
  process.exit(1);
}

const selectedNames = [];
const explicitDirs = [];
for (const a of rawArgs) {
  if (a.startsWith('--')) continue;
  if (MECHANICS[a]) selectedNames.push(a);
  else explicitDirs.push(path.resolve(a));
}
const selected = selectedNames.length ? selectedNames : Object.keys(MECHANICS);

// A report folder's game: from its sampledata/{ff,wow}/ path segment when
// present; folders elsewhere run against both games' mechanics (every
// detection self-gates on its mechanic's signatures, so the wrong game's
// modules just report nothing).
function gamesOfDir(dir) {
  const segs = dir.split(path.sep);
  if (segs.includes('ff')) return ['ff'];
  if (segs.includes('wow')) return ['wow'];
  return ['ff', 'wow'];
}

(async () => {
  const loadedMods = new Map(); // mechanic name -> load() result
  const modFor = (name) => {
    if (!loadedMods.has(name)) loadedMods.set(name, MECHANICS[name].load());
    return loadedMods.get(name);
  };
  const { getFFJobByName } = requireTsFromRoot('lib/ffl-job-data.ts');
  const rulings = mode === 'check' ? loadRulings() : [];
  const failures = []; // check mode: one line per report with differences

  for (const game of ['ff', 'wow']) {
    const mechs = selected.filter((n) => MECHANICS[n].game === game);
    if (mechs.length === 0) continue;

    const dirs = explicitDirs.length
      ? explicitDirs.filter((d) => gamesOfDir(d).includes(game))
      : discoverReportFolders(path.join(ROOT, 'sampledata', game));

    if (dirs.length === 0 && explicitDirs.length === 0) {
      console.log(`No report folders found under sampledata/${game}/ (looked for subdirectories containing meta.json).`);
      console.log(`Fetch one with: node scripts/fetch-${game}-report.js <reportCode>`);
      continue;
    }

    for (const dir of dirs) {
      const loaded = loadReportFolder(dir);
      if (!loaded) { console.log(`${dir} -> no meta.json, skipping`); continue; }
      const { meta, pulls } = loaded;
      const actorMap = buildActorMap(meta);
      const abilityMap = buildAbilityMap(meta);

      console.log('#'.repeat(70));
      console.log(`${meta.title ?? meta.code} (${dir})`);
      console.log(`  ${pulls.length} pull(s)`);

      const ctxs = game === 'ff' ? pulls.map((p) => makeFFPullCtx(p, actorMap, abilityMap, getFFJobByName)) : null;

      currentEntries = [];
      for (const name of mechs) {
        console.log('~'.repeat(70));
        console.log(`~ mechanic: ${name}`);
        currentMechanic = name;
        await MECHANICS[name].run({ mod: modFor(name), dir, meta, pulls, ctxs, actorMap, abilityMap });
      }
      const entries = sortEntries(currentEntries);
      currentEntries = null;
      const code = meta.code ?? path.basename(dir);

      if (mode === 'update') {
        writeSnapshot(game, code, mechs, entries);
      } else if (mode === 'check') {
        console.log('~'.repeat(70));
        const snapshot = readSnapshot(game, code);
        if (!snapshot) {
          console.log(`CHECK ${game}-${code}: NO BASELINE — run \`node scripts/validate.js --update ${dir}\` to create one`);
          failures.push(`${game}-${code}: no baseline`);
        } else {
          // Narrowed runs only compare the mechanics that actually ran.
          const baseline = snapshot.errors.filter((e) => mechs.includes(e.mechanic));
          const diff = diffEntries(baseline, entries);
          const total = diff.added.length + diff.removed.length + diff.changed.length;
          if (total === 0) {
            console.log(`CHECK ${game}-${code}: OK (${entries.length} errors match baseline)`);
          } else {
            console.log(`CHECK ${game}-${code}: ${total} difference(s) vs baseline (+${diff.added.length} -${diff.removed.length} ~${diff.changed.length})`);
            printDiff(diff);
            failures.push(`${game}-${code}: ${total} snapshot difference(s)`);
          }
          const violations = checkRulings(rulings, code, mechs, entries);
          for (const v of violations) {
            const where = [v.ruling.mechanic, v.ruling.boss, v.ruling.pull !== undefined ? `Pull ${v.ruling.pull}` : null].filter(Boolean).join(' ');
            if (v.kind === 'mustFlag') {
              console.log(`  RULING VIOLATED (${where}): expected a flag matching ${JSON.stringify(v.spec)} — none found. Note: ${v.ruling.note ?? '(none)'}`);
            } else {
              console.log(`  RULING VIOLATED (${where}): ${describeEntry(v.entry)} must NOT flag. Note: ${v.ruling.note ?? '(none)'}`);
            }
            failures.push(`${game}-${code}: ruling violation (${v.kind})`);
          }
        }
      }
    }
  }

  if (mode === 'check' || mode === 'update') reportOrphans({ prune: false });

  if (mode === 'check') {
    console.log('#'.repeat(70));
    if (failures.length === 0) {
      console.log('CHECK PASSED — all reports match their baselines and rulings.');
    } else {
      console.log(`CHECK FAILED — ${failures.length} problem(s):`);
      for (const f of failures) console.log(`  ${f}`);
      console.log('If these differences are INTENDED (detection philosophy evolved), verify the diff above is');
      console.log('exactly the intended change, then run `node scripts/validate.js --update` and commit the');
      console.log('snapshot diff. Rulings in expectations/rulings.json must be edited by hand, never regenerated.');
      process.exitCode = 1;
    }
  }
})().catch((err) => { console.error(err); process.exit(1); });
