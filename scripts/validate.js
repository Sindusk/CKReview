// scripts/validate.js — THE unified regression harness for every mechanic
// detection module, replacing the old per-mechanic validate-<mechanic>.js
// scripts (which were ten near-identical copies of the same loop).
//
// Usage (from the repo root):
//   node scripts/validate.js                          # every mechanic, every report
//   node scripts/validate.js forsaken                 # one mechanic, every report
//   node scripts/validate.js forsaken blackhole       # several mechanics
//   node scripts/validate.js sampledata/ff/<code>     # every mechanic, one report
//   node scripts/validate.js stompies sampledata/ff/<code>
//   node scripts/validate.js --check                  # diff output vs expectations/
//   node scripts/validate.js --update                 # regenerate expectations/
//   node scripts/validate.js --prune                  # drop snapshots whose sampledata is gone
//   node scripts/validate.js --list                   # print mechanic names
//
// Args that match a mechanic name select mechanics; anything else is treated
// as a report folder path. With no folder args, every report folder under
// sampledata/ff/ and sampledata/wow/ (any subdirectory containing a
// meta.json, as produced by scripts/fetch-{ff,wow}-report.js) is processed.
//
// ── Expected-output baselines (expectations/, gitignored like sampledata) ──
//
// expectations/ holds log-derived data (real player names, error text), so
// like sampledata/ it stays out of git — it's a local development tool, not
// part of the codebase. A snapshot is only meaningful while its report's
// sampledata exists (without the data, detection can't re-run, so the
// snapshot can never fail again): when a report folder is deleted to free
// space, its snapshot is dead weight — --check/--update warn about such
// orphans, and `node scripts/validate.js --prune` deletes them. Before
// deleting a report, make sure anything it UNIQUELY proved is encoded
// durably (threshold comments with clean/failure extremes, README rules,
// rulings) — the snapshot itself is never the long-term record. Two tiers:
//
// 1. SNAPSHOTS — expectations/<game>-<reportCode>.json, machine-generated by
//    --update. `--check` re-runs detection and reports every added/removed/
//    changed error vs the snapshot. Snapshots are a *reviewed baseline*, not
//    eternal truth: when detection philosophy evolves intentionally (e.g. a
//    severity downgrade), the workflow is: make the change, run --check to
//    confirm the delta is exactly what was intended and nothing else, then
//    --update and commit — the git diff of the snapshot IS the review
//    artifact. Narrowed runs (mechanic and/or report args) check/update only
//    the narrowed subset, merging into existing snapshot files.
//
// 2. RULINGS — expectations/rulings.json, small and hand-curated: specific
//    adjudications the user made during VOD review ("pull 15: only X should
//    flag", "pull 10: Y must NOT flag clipped-by-neighbor"). Checked on
//    every --check run but NEVER touched by --update — a ruling violation
//    means the change contradicts a call the user personally made, and the
//    ruling must be consciously edited (or the change reconsidered), never
//    silently regenerated away. Severity-only philosophy shifts don't touch
//    rulings at all (a ruling pins who flags, not how severely).
//
// mitigation-review is sanity-print only and contributes nothing to
// snapshots; cross-pull summary sections (Black Hole strategy, kick order,
// crystal assignments, Graven layout) are printed but not snapshotted —
// only PullErrors are.
//
// Each mechanic entry in MECHANICS below declares which game it belongs to,
// how to load its detection module(s) (transpiled on the fly from .ts via
// scripts/lib/require-ts.js), and how to run it over one report. Per-pull
// inputs (PlayerInfo[]/DeathEvent[]/etc.) are built once per report through
// a lazy, memoized pull context and shared across all selected mechanics —
// running everything is barely more expensive than running one.
//
// Two timestamp conventions coexist, matching the live pipeline exactly:
// most FF modules receive raw absolute report-ms timestamps, but phase1 and
// graven-image gate on fight-relative windows and receive streams shifted by
// the pull's own earliest event (same as log-transforms.ts's fightStart).
// WoW pulls are always fight-relative (build-wow-players.js shifts them).
//
// No verified expected-results table exists yet for the current sample
// captures — this harness's role is regression protection (no crashes, no
// warnings) plus a readable per-pull error summary to eyeball after any
// mechanic change. Also run `npx tsc --noEmit`.
