// Shared by the two mitigation entries: resolve the report folder to a code,
// load it through the app's own sample-report-store, and transform it with
// the real transformFFReportToPulls. Returns null (with a note) for folders
// the store can't see (i.e. anything outside sampledata/ff/<code>/).
async function loadThroughRealPipeline(mod, dir) {
  const code = path.basename(dir);
  if (!(await mod.store.sampleReportExists('ffl', code))) {
    console.log(`  (skipped: sample-report-store can't load '${code}' — mitigation checks only run on sampledata/ff/<code> folders)`);
    return null;
  }
  const payload = await mod.store.loadSampleReport('ffl', code);
  if (payload.source !== 'ffl') return null;
  const abilityMap = mod.lt.buildFFLAbilityMap(payload.report.masterData.abilities);
  return mod.lt.transformFFReportToPulls(payload.fightDataList, abilityMap, code);
}

// ── expectations: snapshots + rulings ───────────────────────────────────────

const EXPECTATIONS_DIR = path.join(ROOT, 'expectations');
const RULINGS_PATH = path.join(EXPECTATIONS_DIR, 'rulings.json');

function snapshotPath(game, code) {
  return path.join(EXPECTATIONS_DIR, `${game}-${code}.json`);
}

function readSnapshot(game, code) {
  const p = snapshotPath(game, code);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

// --update: replace the snapshot's entries for the mechanics that ran,
// keeping entries of mechanics that didn't (so narrowed runs don't wipe the
// rest of the file).
function writeSnapshot(game, code, mechsRun, entries) {
  const existing = readSnapshot(game, code);
  const kept = (existing?.errors ?? []).filter((e) => !mechsRun.includes(e.mechanic));
  const merged = sortEntries([...kept, ...entries]);
  fs.mkdirSync(EXPECTATIONS_DIR, { recursive: true });
  fs.writeFileSync(snapshotPath(game, code), JSON.stringify({ report: code, game, errors: merged }, null, 1) + '\n');
  console.log(`  wrote expectations/${game}-${code}.json (${merged.length} entries${kept.length ? `, ${kept.length} kept from mechanics not run` : ''})`);
}

// Multiset diff of baseline vs actual, then pair up removed+added entries
// that share an identity (mechanic/boss/pull/ruleId/player) so an
// intentional change (e.g. a severity downgrade, a reworded description)
// reads as one "~ changed" line with the differing fields, not an opaque
// remove+add pair.
function diffEntries(baseline, actual) {
  const key = (e) => JSON.stringify(e);
  const counts = new Map();
  for (const e of baseline) counts.set(key(e), (counts.get(key(e)) ?? 0) + 1);
  const added = [];
  for (const e of actual) {
    const k = key(e);
    if ((counts.get(k) ?? 0) > 0) counts.set(k, counts.get(k) - 1);
    else added.push(e);
  }
  const removed = [];
  const emitted = new Map();
  for (const e of baseline) {
    const k = key(e);
    if ((emitted.get(k) ?? 0) < (counts.get(k) ?? 0)) {
      removed.push(e);
      emitted.set(k, (emitted.get(k) ?? 0) + 1);
    }
  }

  const identity = (e) => [e.mechanic, e.boss, e.pull, e.ruleId, e.player].join('|');
  const removedByIdentity = new Map();
  for (const e of removed) {
    const id = identity(e);
    if (!removedByIdentity.has(id)) removedByIdentity.set(id, []);
    removedByIdentity.get(id).push(e);
  }
  const changed = [];
  const pureAdded = [];
  for (const e of added) {
    const pool = removedByIdentity.get(identity(e));
    if (pool && pool.length) changed.push({ before: pool.shift(), after: e });
    else pureAdded.push(e);
  }
  const pureRemoved = [...removedByIdentity.values()].flat();
  return { added: pureAdded, removed: pureRemoved, changed };
}

const clip = (s, n = 90) => (s && s.length > n ? s.slice(0, n) + '…' : s);

function describeEntry(e) {
  return `${e.mechanic} ${e.boss} Pull ${e.pull} [${e.ruleId}] t=${e.t} ${e.player ?? '(raid)'}: ${clip(e.description ?? e.name ?? '')}`;
}

function printDiff(diff) {
  for (const e of diff.removed) console.log(`  - ${describeEntry(e)}`);
  for (const e of diff.added) console.log(`  + ${describeEntry(e)}`);
  for (const { before, after } of diff.changed) {
    const fields = ['severity', 't', 'name', 'description'].filter((f) => before[f] !== after[f]);
    const detail = fields.map((f) => `${f}: ${clip(String(before[f]), 60)} -> ${clip(String(after[f]), 60)}`).join('; ');
    console.log(`  ~ ${before.mechanic} ${before.boss} Pull ${before.pull} [${before.ruleId}] ${before.player ?? '(raid)'} — ${detail}`);
  }
}

// Rulings (expectations/rulings.json): hand-curated adjudications from VOD
// review, checked on every --check run and NEVER regenerated by --update.
// Each ruling: { report, mechanic?, boss?, pull?, mustFlag: [...],
// mustNotFlag: [...], note?, date? } — mustFlag/mustNotFlag items match an
// entry when every field they specify (ruleId, player, severity, ...)
// equals the entry's; the ruling's own report/mechanic/boss/pull scope the
// candidate entries first.
function loadRulings() {
  if (!fs.existsSync(RULINGS_PATH)) return [];
  return JSON.parse(fs.readFileSync(RULINGS_PATH, 'utf8')).rulings ?? [];
}

function checkRulings(rulings, code, mechsRun, entries) {
  const violations = [];
  for (const r of rulings) {
    if (r.report !== code) continue;
    if (r.mechanic && !mechsRun.includes(r.mechanic)) continue; // narrowed run didn't exercise it
    const scoped = entries.filter((e) =>
      (r.mechanic === undefined || e.mechanic === r.mechanic) &&
      (r.boss === undefined || e.boss === r.boss) &&
      (r.pull === undefined || e.pull === r.pull));
    const matches = (spec) => scoped.filter((e) => Object.entries(spec).every(([f, v]) => e[f] === v));
    for (const spec of r.mustFlag ?? []) {
      if (matches(spec).length === 0) violations.push({ ruling: r, kind: 'mustFlag', spec });
    }
    for (const spec of r.mustNotFlag ?? []) {
      for (const e of matches(spec)) violations.push({ ruling: r, kind: 'mustNotFlag', spec, entry: e });
    }
  }
  return violations;
}

// Snapshots (and rulings) for reports whose sampledata folder has been
// deleted are unverifiable — detection can't re-run against them, so they
// can never fail again. --check/--update warn about them; --prune removes
// orphaned snapshots (rulings are hand-curated, so orphaned ones are only
// LISTED for hand-removal — their lesson may still need distilling into a
// module comment first).
function findOrphanSnapshots() {
  if (!fs.existsSync(EXPECTATIONS_DIR)) return [];
  const orphans = [];
  for (const f of fs.readdirSync(EXPECTATIONS_DIR)) {
    const m = f.match(/^(ff|wow)-(.+)\.json$/);
    if (!m) continue;
    if (!fs.existsSync(path.join(ROOT, 'sampledata', m[1], m[2]))) {
      orphans.push({ file: path.join(EXPECTATIONS_DIR, f), name: f, game: m[1], code: m[2] });
    }
  }
  return orphans;
}

function findOrphanRulings() {
  return loadRulings().filter((r) =>
    !fs.existsSync(path.join(ROOT, 'sampledata', 'ff', r.report)) &&
    !fs.existsSync(path.join(ROOT, 'sampledata', 'wow', r.report)));
}

function reportOrphans({ prune }) {
  const orphans = findOrphanSnapshots();
  const orphanRulings = findOrphanRulings();
  if (orphans.length === 0 && orphanRulings.length === 0) {
    if (prune) console.log('No orphaned snapshots or rulings — every expectations entry has its sampledata.');
    return;
  }
  console.log('#'.repeat(70));
  for (const o of orphans) {
    if (prune) {
      fs.unlinkSync(o.file);
      console.log(`PRUNED expectations/${o.name} (sampledata/${o.game}/${o.code}/ no longer exists)`);
    } else {
      console.log(`ORPHANED SNAPSHOT expectations/${o.name} — sampledata/${o.game}/${o.code}/ is gone; run --prune to remove`);
    }
  }
  for (const r of orphanRulings) {
    console.log(`ORPHANED RULING for report ${r.report} (${r.note ?? 'no note'}) — sampledata deleted; ` +
      'hand-remove it from expectations/rulings.json once its lesson is encoded in the module/README');
  }
}

