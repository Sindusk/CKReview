#!/usr/bin/env node
// scripts/sync-action-levels.js
//
// Refreshes lib/damage/ffxiv/action-levels.ts: the level each action in
// lib/damage/ffxiv/xiva-data.ts is learned at (XIVAPI v2, Action sheet
// ClassJobLevel). Older ultimates sync players below the cap
// (lib/damage/ffxiv/patches.ts levelOf), so checks that lean on an action
// learned above the sync level are skipped there (docs/dps-analysis.md).
//
// XIVAPI is read-only and public; the values are checked to be integers
// and written with JSON.stringify. Rerun after scripts/sync-xiva-data.js.
//
// Usage: node scripts/sync-action-levels.js

const fs = require('fs');
const path = require('path');
const { requireTsFromRoot, ROOT } = require('./lib/require-ts');

const OUT = path.join(ROOT, 'lib', 'damage', 'ffxiv', 'action-levels.ts');
const { XIVA_ACTIONS } = requireTsFromRoot('lib/damage/ffxiv/xiva-data.ts');
// Item ids (tinctures) and pseudo-abilities aren't Action rows.
const ids = [...new Set(Object.values(XIVA_ACTIONS).filter((a) => a.job !== 'ITEMS' && a.id < 100000).map((a) => a.id))].sort((a, b) => a - b);

async function main() {
  const levels = {};
  for (let i = 0; i < ids.length; i += 100) {
    const rows = ids.slice(i, i + 100);
    const url = `https://v2.xivapi.com/api/sheet/Action?rows=${rows.join(',')}&fields=Name,ClassJobLevel`;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`XIVAPI ${res.status} for rows ${rows[0]}..`);
    const body = await res.json();
    for (const r of body.rows ?? []) {
      const lv = r.fields?.ClassJobLevel;
      if (Number.isInteger(r.row_id) && Number.isInteger(lv) && lv > 0) levels[r.row_id] = lv;
    }
  }
  const body = Object.entries(levels).map(([id, lv]) => `  ${id}: ${lv},`).join('\n');
  fs.writeFileSync(OUT, `// lib/damage/ffxiv/action-levels.ts
//
// GENERATED by scripts/sync-action-levels.js from XIVAPI v2 (Action sheet
// ClassJobLevel), ${new Date().toISOString().slice(0, 10)}. Don't edit by hand.
//
// Action id -> the level it's learned at, for every action in xiva-data.ts.
// A trait-upgraded action carries its own level (Damnation 92; the
// Vengeance it replaces 38).

export const ACTION_LEVELS: Record<number, number> = {
${body}
};
`);
  console.log(`${Object.keys(levels).length} of ${ids.length} actions -> ${path.relative(ROOT, OUT)}`);
}

main().catch((e) => { console.error(e); process.exit(1); });
